// ============================================================
// 3. Function to look up Turkish by reference
// ============================================================
function lookup(ref) {
  let t = quranTr[ref]
  if (t) return t
  const canonical = aliasMap[ref]
  if (canonical) {
    t = quranTr[canonical]
    if (t) return t
  }
  return null
}

// ============================================================
// 4. Apply translations
// ============================================================
let translated = 0
let notFound = []

for (const [cid, ch] of Object.entries(tr.chapters)) {
  if (!ch.introVerses) continue
  for (let vi = 0; vi < ch.introVerses.length; vi++) {
    const v = ch.introVerses[vi]
    if (/[ığüşöçİĞÜŞÖÇ]/.test(v.text)) continue

    const turkishText = lookup(v.reference)
    if (turkishText) {
      v.text = turkishText
      translated++
    } else {
      notFound.push({ cid, reference: v.reference, text: v.text.substring(0, 80) })
    }
  }
}

console.log(`Translated ${translated} verses`)
if (notFound.length > 0) {
  console.log(`\nNOT FOUND (${notFound.length}):`)
  for (const nf of notFound) {
    console.log(`  Ch ${nf.cid}: "${nf.reference}" — ${nf.text}...`)
  }
}

tr.meta.generated = new Date().toISOString()
writeFileSync(trFilePath, JSON.stringify(tr, null, 2) + '\n', 'utf-8')
console.log(`\n✓ Written to src/lib/translations/tr.json`)
